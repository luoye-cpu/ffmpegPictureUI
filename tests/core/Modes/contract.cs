                    // （linear≈0.0169）必被采到；R=G=B ⇒ GMO 对中性色严格 no-op（见 GamutMapScalar 的性质），
                    // 于是 16bit 差值里只剩"曲线口径"这一项，没有别的算子混进来。
                    const int n709 = 65536;
                    var in709 = new byte[n709 * 6];
                    for (int i = 0; i < n709; i++)
