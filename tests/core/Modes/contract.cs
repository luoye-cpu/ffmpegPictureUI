                    var c7bZim = CE.Plan(lin2020, bt709Sdr, Pol709(true));
                    Check(c7bStd.Backend == CB.InProcess && c7bZim.Backend == CB.InProcess,
                        $"C7b 前提：两格都必须落在 H1（实 std={c7bStd.Backend} / zimg={c7bZim.Backend}）");

