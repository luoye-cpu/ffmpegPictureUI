                    // null 只有在「本仓**故意**不收录」时才正确，且必须逐个点名理由：
                    //   film     = 未收录（lcms 有原色但残差 2.1e-4，精度不足以填表）
                    //   smpte428 = **xy 参数化表达不了**（H.273 蓝原色 y=0 ⇒ 归一化退化）⇒ 只能不收录
