                if (tok == "bt709")
                {
                    // 同 token 的契约就是 null（=不映射）；把它当"缺矩阵"判红是我第一版的错向断言。
                    Check(got == null, "bt709→bt709 必须 null（同原色 = 不映射，绝不生成单位阵去乘一遍）");
                    continue;
